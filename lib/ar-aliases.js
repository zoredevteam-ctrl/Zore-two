const arNormalize = s => (s || '')
    .trim()
    .toLowerCase()
    .replace(/[\u064B-\u0652]/g, '')
    .replace(/[أإآ]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/\s+/g, '_')

const resolveAlias = s => AR_ALIASES[arNormalize(s)] || s

